/**
 * Renders the checklist state + findings + verdict into the human-facing
 * `docs/deployment/READINESS-CHECKLIST.md`. The markdown is a PRESENTATION
 * projection of the evaluated report — never an authority feeding back in.
 */

import type { ChecklistItem, Environment, Finding, Verdict } from '../checklist/checklist.model';

/** The per-environment status cell for an item (▪ for not-applicable). */
function statusCell(item: ChecklistItem, env: Environment): string {
  const result = item.results[env];
  if (result !== undefined) {
    return result.status;
  }
  return item.probes[env] === null ? 'N/A' : '—';
}

/** Render the full checklist markdown artifact. */
export function renderChecklistMarkdown(
  items: readonly ChecklistItem[],
  findings: readonly Finding[],
  verdict: Verdict,
): string {
  const lines: string[] = [];
  lines.push('# Deployment Readiness Checklist');
  lines.push('');
  lines.push('> Generated by `tools/full-audit` — a re-audit artifact, not a one-off.');
  lines.push('> Each item separates its invariant (same across environments) from its');
  lines.push('> per-environment probe. Status is tri-state: `PASS | FAIL | N/A`.');
  lines.push('');
  lines.push(`**Verdict: ${verdict}**`);
  lines.push('');
  lines.push('| Category | Invariant | Owner | Mandatory | local | vps |');
  lines.push('|---|---|---|---|---|---|');
  for (const item of sortByCategory(items)) {
    lines.push(
      `| ${item.invariant.category} | ${escape(item.invariant.description)} | ${item.owner} | ` +
        `${item.mandatory ? 'yes' : 'no'} | ${statusCell(item, 'local')} | ${statusCell(item, 'vps')} |`,
    );
  }
  lines.push('');
  lines.push('## Findings');
  lines.push('');
  if (findings.length === 0) {
    lines.push('_No findings._');
  } else {
    lines.push('| Reason | Invariant | Environment | Owner | Evidence |');
    lines.push('|---|---|---|---|---|');
    for (const finding of findings) {
      lines.push(
        `| ${finding.reason} | ${finding.invariantId} | ${finding.environment} | ` +
          `${finding.owner} | ${escape(finding.evidence)} |`,
      );
    }
  }
  lines.push('');
  return lines.join('\n');
}

/** Stable category ordering for a readable table. */
function sortByCategory(items: readonly ChecklistItem[]): ChecklistItem[] {
  return [...items].sort((a, b) =>
    `${a.invariant.category}:${a.invariant.id}`.localeCompare(`${b.invariant.category}:${b.invariant.id}`),
  );
}

/** Escape pipe characters so table cells never break the markdown grid. */
function escape(text: string): string {
  return text.replace(/\|/g, '\\|');
}
